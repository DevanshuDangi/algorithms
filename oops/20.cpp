// 1️⃣Encapsulation – Data Hiding & Access Control
// 🔹 Definition: Encapsulation is the process of hiding data inside a class and only allowing controlled access via methods (getters & setters).
// 🔹 Purpose: Protects data from unintended modification and improves security.

// 2️⃣ Abstraction – Hiding Implementation Details
// 🔹 Definition: Abstraction means exposing only essential features of an object while hiding complex implementation details.
// 🔹 Purpose: Simplifies code usage by providing clean interfaces.

// 3️⃣ Inheritance – Code Reusability & Hierarchy
// 🔹 Definition: Inheritance allows one class (child class) to acquire properties and behaviors of another class (parent class).
// 🔹 Purpose: Promotes code reusability and hierarchical relationships.

// 4️⃣ Polymorphism – Multiple Forms of a Function
// 🔹 Definition: Polymorphism allows the same function name to perform different behaviors based on the object.
// 🔹 Purpose: Improves flexibility and scalability of code